ASSET_KINDS = {'i': 'pictures', 'zi': 'fonts', 'gmov': 'animations'}
TEXT, HEXV = 't', 'h'


def _slug(text, fallback):
    key = re.sub(r'[^A-Za-z0-9_.\-]', '_', text) or fallback
    return key


def _layout_of(obj):
    out = []
    for a in obj.attrs:
        if a.name in M.TEXT_ATTRS:
            out.append([a.name, TEXT])
        elif len(a.value) in (1, 2, 4):
            out.append([a.name, len(a.value)])
        else:
            out.append([a.name, HEXV])
    return out


