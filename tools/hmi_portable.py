class PortableCompiler:
    def __init__(self, root, cfg):
        self.root, self.cfg = Path(root).resolve(), cfg
        C._dict(cfg, ('format', 'portable', 'project', 'layouts', 'pages', 'pictures', 'fonts', 'animations', 'program',
                      'acknowledge'), 'config', ('format', 'portable', 'project', 'pages', 'pictures', 'fonts'))
        proj = C._dict(cfg['project'], ('header', 'index_order'), 'project', ('header',))
        try:
            self.header = bytes.fromhex(proj['header'])
        except (ValueError, TypeError) as e:
            raise C.ConfigError('project.header must be hex') from e
        if len(self.header) != M.INDEX_HEADER_SIZE:
            raise C.ConfigError('project.header must have %d bytes' % M.INDEX_HEADER_SIZE)
        self.order = C._list(proj.get('index_order', ['i', 'zi', 'gmov', 'pa']), 'project.index_order')
        self.layouts = C._map(cfg.get('layouts', {}), 'layouts')
        self.findings = []
        self.page_specs = self._pages()
        self.pics = self._entries('pictures', ('key', 'source'), 'picture')
        self.fonts = self._entries('fonts', ('key', 'source'), 'font')
        self.anims = self._entries('animations', ('key', 'gmov', 'gmovs', 'frames', 'fps', 'opaque'), 'animation', source=False)
        self.page_ids = {p['key']: i for i, p in enumerate(self.page_specs)}
        self.pic_ids = {e['key']: i for i, e in enumerate(self.pics)}
        self.font_ids = {e['key']: i for i, e in enumerate(self.fonts)}
        self.anim_ids = {e['key']: i for i, e in enumerate(self.anims)}
        self.obj_ids = {p['key']: {o['key']: n for n, o in enumerate(p['objects'], 1)} for p in self.page_specs}
        if not 1 <= len(self.page_specs) <= 255:
            raise C.ConfigError('A project needs 1..255 pages')
        if len(self.pics) > 65535 or len(self.fonts) > 256:
            raise C.ConfigError('Too many pictures (max 65535) or fonts (max 256)')
        self.maps = _identity_maps(len(self.page_specs), len(self.pics), len(self.font_ids),
                                   [len(p['objects']) + 1 for p in self.page_specs], [p['name'] for p in self.page_specs])
        self.page_size = None

    # -- specs
    def _read(self, rel, label):
        return P._safe_workspace_path(self.root, rel, label + ' ' + str(rel)).read_bytes()

    def _entries(self, section, allowed, label, source=True):
        out, keys = [], set()
        for n, e in enumerate(C._list(self.cfg[section] if section in self.cfg else [], section)):
            where = '%s[%d]' % (section, n)
            C._dict(e, allowed, where, ('key',))
            key = C._key(e['key'], where + '.key')
            if key in keys:
                raise C.ConfigError('Duplicate %s key %r' % (label, key))
            keys.add(key)
            out.append(dict(e, where=where))
        return out

    def _pages(self):
        specs, keys = [], set()
        for n, entry in enumerate(C._list(self.cfg['pages'], 'pages')):
            where = 'pages[%d]' % n
            C._dict(entry, ('key', 'content'), where, ('key', 'content'))
            key = C._key(entry['key'], where + '.key')
            if key in keys:
                raise C.ConfigError('Duplicate page key %r' % key)
            keys.add(key)
            c = C._dict(entry['content'], ('mode', 'path', 'name', 'header', 'root', 'objects'), where + '.content', ('mode',))
            if c['mode'] == 'json':
                doc = C.load_json(P._safe_workspace_path(self.root, c.get('path', ''), 'Page content'), str(c.get('path')))
            elif c['mode'] == 'inline':
                doc = {k: c[k] for k in c if k != 'mode'}
            else:
                raise C.ConfigError('%s: portable pages use content mode json or inline' % where)
            C._dict(doc, ('name', 'header', 'root', 'objects'), where + ' content', ('name',))
            name = doc['name']
            if not isinstance(name, str) or not name or len(name.encode('utf8')) > 16 or '\0' in name:
                raise C.ConfigError('%s: invalid page name %r' % (where, name))
            if name in {s['name'] for s in specs}:
                raise C.ConfigError('%s: duplicate page name %r' % (where, name))
            objects, okeys = [], set()
            for m, o in enumerate(C._list(doc.get('objects', []), where + '.objects')):
                w = '%s.objects[%d]' % (where, m)
                C._dict(o, ('key', 'type', 'attributes', 'events', 'layout', 'extra', 'tail'), w, ('key', 'type'))
                k = C._key(o['key'], w + '.key')
                if k in okeys or k == '(page)':
                    raise C.ConfigError('%s: duplicate object key %r' % (w, k))
                okeys.add(k)
                C._map(o.get('attributes', {}), w + '.attributes')
                C._map(o.get('events', {}), w + '.events')
                objects.append(dict(o, where=w))
            if len(objects) + 1 > M.MAX_OBJECTS:
                raise C.ConfigError('%s: a page holds at most %d components besides the page object' % (where, M.MAX_OBJECTS - 1))
            root = C._dict(doc.get('root', {}), ('attributes', 'events', 'layout', 'extra', 'tail'), where + '.root')
            specs.append({'key': key, 'name': name, 'header': doc.get('header', {}), 'root': root, 'objects': objects,
                          'where': where})
        return specs

    # -- placeholders
    def resolve(self, kind, key):
        try:
            if kind == 'page':
                return self.page_ids[key]
            if kind == 'pagename':
                return self.page_specs[self.page_ids[key]]['name']
            if kind == 'picture':
                return self.pic_ids[key]
            if kind == 'font':
                return self.font_ids[key]
            if kind == 'animation':
                return self.anim_ids[key]
            pk, _, ok = key.partition('/')
            if kind == 'obj':
                return 0 if ok in ('', '(page)') else self.obj_ids[pk][ok]
            if kind == 'objname':
                ps = self.page_specs[self.page_ids[pk]]
                if ok in ('', '(page)'):
                    return ps['name']
                return C._name_text(ps['objects'][self.obj_ids[pk][ok] - 1]['attributes'].get('objname'))
        except KeyError as e:
            raise C.ConfigError('Unknown reference ${%s:%s}' % (kind, key)) from e
        raise C.ConfigError('Unknown reference kind ${%s:%s}' % (kind, key))

    def _line(self, raw, site, page_index=None):
        text = raw.decode('utf8', 'surrogateescape')
        rw = R.Rewriter(self.maps, page_index, forbid=True)
        rw.run(text)
        for f in rw.findings:
            if f.kind == 'newref':
                self.findings.append('%s: %s\n    %s' % (site, f.message, text.strip()))
        return R.expand(text, self.resolve).encode('utf8', 'surrogateescape')

    # -- objects
    def _ref(self, value, domain, where):
        label = {'pic': 'picture', 'anim': 'animation'}.get(domain, domain)
        table = {'page': self.page_ids, 'pic': self.pic_ids, 'font': self.font_ids, 'anim': self.anim_ids}[domain]
        kind, _, key = str(value['$ref']).partition(':')
        if kind != label:
            raise C.ConfigError('%s: this attribute takes a %s reference, not %r' % (where, label, value['$ref']))
        if key not in table:
            raise C.ConfigError('%s: unknown %s key %r' % (where, label, key))
        return table[key]

    def build_object(self, spec, code, object_id, where, root=False):
        layout = spec.get('layout') or self.layouts.get(str(code))
        creatable = code in F.CREATABLE
        if layout is None:
            if not creatable:
                raise C.ConfigError('%s: no layout is known for type %d' % (where, code))
            layout = [[n, w if w else TEXT] for n, w, _d, _a in F.profile(code)[0]]
        defaults = {}
        if creatable:
            defaults = {n: d for n, _w, d, _a in F.profile(code)[0] if d is not None}
        values = dict(spec.get('attributes', {}))
        names = [n for n, _ in layout]
        for k in values:
            if k not in names:
                raise C.ConfigError('%s: unknown attribute %r for this component' % (where, k))
        attrs = []
        for name, width in layout:
            if name == 'type':
                raw = bytes((code,)) if width == 1 else M.encode_value(name, code, width)
            elif name == 'id':
                raw = M.encode_value(name, object_id, width)
            elif name in values:
                value = values[name]
                dom = R.attr_domain(code, name)
                if isinstance(value, dict) and set(value) == {'$ref'}:
                    if not dom:
                        raise C.ConfigError('%s.%s is not a reference attribute' % (where, name))
                    value = self._ref(value, dom[0], '%s.%s' % (where, name))
                elif dom and isinstance(value, int) and not isinstance(value, bool) and value != dom[1] \
                        and 0 <= value < {'pic': len(self.pics), 'font': len(self.fonts), 'page': len(self.page_specs),
                                          'anim': len(self.anims)}[dom[0]]:
                    raise C.ConfigError('%s.%s: write {"$ref": "%s:key"} instead of the number %d' % (
                        where, name, {'pic': 'picture', 'anim': 'animation'}.get(dom[0], dom[0]), value))
                raw = M.encode_value(name, value, width if width in (1, 2, 4) else None)
            elif name in ('endx', 'endy') and all(k in values for k in (('x', 'w') if name == 'endx' else ('y', 'h'))):
                a_, b_ = ('x', 'w') if name == 'endx' else ('y', 'h')
                raw = M.encode_value(name, values[a_] + values[b_] - 1, width)
            elif name in defaults:
                raw = defaults[name]
            elif root and name == 'objname':
                raw = None
            else:
                raise C.ConfigError('%s: attribute %r is missing' % (where, name))
            attrs.append(M.Attr(name, raw if raw is not None else b''))
        events = []
        for label, lines in spec.get('events', {}).items():
            if not label.startswith('codes'):
                raise C.ConfigError('%s: event names start with "codes" (got %r)' % (where, label))
            events.append(M.Event(label, [self._line(x, '%s/%s#%d' % (where, label, i + 1)) for i, x in
                                          enumerate(C._event_lines(lines, '%s.events.%s' % (where, label)))]))
        if creatable and not events:
            events = [M.Event(l, []) for l in F.profile(code)[1]]
        try:
            tail = bytes.fromhex(spec['tail']) if 'tail' in spec else b'\0\0\0\0'
        except (ValueError, TypeError) as e:
            raise C.ConfigError('%s: tail must be hex' % where) from e
        extra = spec.get('extra', 0)
        if isinstance(extra, bool) or not isinstance(extra, int) or not 0 <= extra < 1 << 32:
            raise C.ConfigError('%s: extra must be a u32' % where)
        return M.Obj(attrs, events, tail, extra)

    def build_page(self, ps):
        where = ps['where']
        hdr = bytearray(M.PAGE_HEADER_SIZE)
        h = C._map(ps['header'], where + '.header')
        try:
            hdr[16:24] = bytes.fromhex(h.get('lock', '00' * 8)).ljust(8, b'\0')[:8]
            hdr[40:56] = bytes.fromhex(h.get('writer', '00' * 16)).ljust(16, b'\0')[:16]
        except (ValueError, TypeError) as e:
            raise C.ConfigError('%s.header must be hex' % where) from e
        root_spec = dict(ps['root'])
        attrs = dict(root_spec.get('attributes', {}))
        attrs.setdefault('objname', ps['name'])
        root_spec['attributes'] = attrs
        if self.page_size and not any(k in attrs for k in ('w', 'h')):
            attrs.update(w=self.page_size[0], h=self.page_size[1])
        attrs.setdefault('x', 0)
        attrs.setdefault('y', 0)
        root = self.build_object(root_spec, 121, 0, where + '.root', root=True)
        objs = [root]
        for n, so in enumerate(ps['objects'], 1):
            w = '%s.objects[%d](%s)' % (where, n - 1, so['key'])
            objs.append(self.build_object(so, C._type_any(so['type'], w), n, w))
        names = set()
        for o in objs[1:]:
            nm = o.get('objname').value.decode('utf8', 'replace') if o.get('objname') else None
            if nm in names:
                raise C.ConfigError('%s: duplicate component name %r' % (where, nm))
            names.add(nm)
        page = M.Page(bytes(hdr), objs)
        try:
            page.name = ps['name']
        except M.ModelError as e:
            raise C.ConfigError('%s: %s' % (where, e)) from e
        return page

    # -- all
    def compile(self):
        for ps in self.page_specs:        # page size for new pages: the first page that states one
            w, h = ps['root'].get('attributes', {}).get('w'), ps['root'].get('attributes', {}).get('h')
            if isinstance(w, int) and isinstance(h, int):
                self.page_size = (w, h)
                break
        files, final = {}, {'i': [], 'zi': [], 'gmov': [], 'pa': []}
        counters = {'i': 0, 'zi': 0, 'gmov': 0, 'pa': 0}

        def name(kind, ext):
            n = counters[kind]
            counters[kind] += 1
            final[kind].append('%d.%s' % (n, ext))
            return '%d.%s' % (n, ext)
        for e in self.pics:
            src = C._dict(e.get('source', {}), ('png',), e['where'] + '.source', ('png',))
            try:
                compiled, source = IMG.encode_png(self._read(src['png'], 'Picture source'))
            except ValueError as exc:
                raise C.ConfigError('%s: %s' % (e['where'], exc)) from exc
            n = name('i', 'i')
            files[n], files[n + 's'] = compiled, source
        for e in self.fonts:
            src = C._dict(e.get('source', {}), ('zi', 'ttf', 'height', 'chars', 'chars_file', 'layout', 'bpp', 'name', 'size',
                                                'font_index'), e['where'] + '.source')
            if 'zi' in src:
                data = self._read(src['zi'], 'Font')
            elif 'ttf' in src:
                from hmi_font import encode_ttf
                chars = src.get('chars')
                if 'chars_file' in src:
                    chars = P._parse_chars_file(P._safe_workspace_path(self.root, src['chars_file'], 'Character file'))
                try:
                    data = encode_ttf(str(P._safe_workspace_path(self.root, src['ttf'], 'Font source')), height=src.get('height'),
                                      chars=chars, name=src.get('name'), bpp=src.get('bpp'), size=src.get('size'),
                                      font_index=src.get('font_index', 0), layout=src.get('layout'))
                except ValueError as exc:
                    raise C.ConfigError('%s: %s' % (e['where'], exc)) from exc
            else:
                raise C.ConfigError('%s needs source.zi or source.ttf' % e['where'])
            files[name('zi', 'zi')] = data
        for e in self.anims:
            if 'frames' in e:
                if 'gmov' in e or 'gmovs' in e:
                    raise C.ConfigError('%s: use either frames or gmov/gmovs' % e['where'])
                if not isinstance(e.get('opaque', False), bool):
                    raise C.ConfigError('%s.opaque must be true or false' % e['where'])
                frames = C._list(e['frames'], e['where'] + '.frames')
                pngs, ms = [], []
                for k, fr in enumerate(frames):
                    C._dict(fr, ('png', 'ms'), '%s.frames[%d]' % (e['where'], k), ('png', 'ms'))
                    pngs.append(self._read(fr['png'], 'Animation frame'))
                    ms.append(fr['ms'])
                try:
                    gmov, gmovs = ANIM.encode_animation(pngs, ms, e.get('fps', 10), opaque=e.get('opaque', False) is True)
                except ValueError as exc:
                    raise C.ConfigError('%s: %s' % (e['where'], exc)) from exc
                n = name('gmov', 'gmov')
                files[n], files[n + 's'] = gmov, gmovs
                continue
            if 'gmov' not in e:
                raise C.ConfigError('%s needs "frames" or "gmov"' % e['where'])
            n = name('gmov', 'gmov')
            files[n] = self._read(e['gmov'], 'Animation')
            if 'gmovs' in e:
                files[n + 's'] = self._read(e['gmovs'], 'Animation source')
        for ps in self.page_specs:
            data = bytearray(self.build_page(ps).to_bytes())
            if data[21] == I.FILE_ID and data[22] == I.FORMAT_VERSION:     # keep the writer version of an exported page
                struct.pack_into('<I', data, 0, I.page_checksum(data))
            files[name('pa', 'pa')] = bytes(data)
        program = self.cfg.get('program')
        if program is not None:
            text = self._read(program, 'Program').decode('utf8', 'surrogateescape')
            out = []
            for n, line in enumerate(text.splitlines(True), 1):
                body = line.rstrip('\r\n')
                out.append(self._line(body.encode('utf8', 'surrogateescape'), 'Program.s#%d' % n).decode('utf8', 'surrogateescape')
                           + line[len(body):])
            files['Program.s'] = ''.join(out).encode('utf8', 'surrogateescape')
        if self.findings:
            raise C.ConfigError('Reference problems:\n  ' + '\n  '.join(self.findings[:20]))
        order = [k for k in self.order if k in final] + [k for k in final if k not in self.order]
        records = [(k, n) for k in order for n in final[k]]
        index = M.Index(self.header, [], b'')
        try:
            index.records = [M.Index.make_record(k, n) for k, n in records]
            files['main.HMI'] = index.to_bytes()
        except M.ModelError as e:
            raise C.ConfigError(str(e)) from e
        out_files = {}
        for kind in ('i', 'zi', 'gmov', 'pa'):
            for n in final[kind]:
                out_files[n] = files[n]
                if n + 's' in files:
                    out_files[n + 's'] = files[n + 's']
        for n in ('Program.s', 'main.HMI'):
            if n in files:
                out_files[n] = files[n]
        if len(out_files) > M.MAX_RECORDS:
            raise C.ConfigError('The project would exceed %d files' % M.MAX_RECORDS)
        return C.Candidate(out_files, set(out_files), {
            'portable': True, 'pages': len(self.page_specs), 'pictures': len(self.pics), 'fonts': len(self.fonts),
            'animations': len(self.anims), 'files': len(out_files)})


def compile_portable(directory, cfg):
    try:
        return PortableCompiler(directory, cfg).compile()
    except C.ConfigError:
        raise
    except (M.ModelError, ValueError) as e:
        raise C.ConfigError(str(e)) from e
    except (TypeError, AttributeError, KeyError, IndexError) as e:
        raise C.ConfigError('Malformed config (%s: %s)' % (type(e).__name__, e)) from e
