class _Symbols:
    """Final-id -> placeholder tables for one exported project (ids are positions in the exported lists)."""

    def __init__(self, page_keys, pic_keys, font_keys, obj_keys, anim_keys=()):
        self.page_keys, self.pic_keys, self.font_keys, self.obj_keys = page_keys, pic_keys, font_keys, obj_keys
        self.anim_keys = anim_keys

    def ref(self, domain, value):
        keys = {'page': self.page_keys, 'pic': self.pic_keys, 'font': self.font_keys, 'anim': self.anim_keys}[domain]
        label = {'pic': 'picture', 'anim': 'animation'}.get(domain, domain)
        return '%s:%s' % (label, keys[value]) if 0 <= value < len(keys) else None

    def placeholder(self, domain, value, comp_page):
        if domain == 'comp':
            if comp_page is None or not 0 <= comp_page < len(self.obj_keys) or not 0 <= value < len(self.obj_keys[comp_page]):
                return None
            return '${obj:%s/%s}' % (self.page_keys[comp_page], self.obj_keys[comp_page][value])
        ref = self.ref(domain, value)
        return '${%s}' % ref if ref else None


def _identity_maps(page_count, pic_count, font_count, object_counts, page_names):
    ident = lambda n: {i: i for i in range(n)}
    return R.Maps(ident(page_count), ident(pic_count), ident(font_count), {i: ident(c) for i, c in enumerate(object_counts)},
                  dict(enumerate(page_names)), page_names, {i: {} for i in range(page_count)},
                  {i: set() for i in range(page_count)}, set())


def export_portable(source, destination):
    source, destination = Path(source), Path(destination)
    if P._lexists(destination):
        raise FileExistsError('Destination already exists: %s' % destination)
    files = H.read_container(source.read_bytes())
    if 'main.HMI' not in files:
        raise C.ConfigError('The project has no main.HMI')
    index = M.parse_index(files['main.HMI'])
    pairs = index.pairs()
    kinds = {k for k, _ in pairs}
    if kinds - {'pa', 'i', 'zi', 'gmov'}:
        raise C.ConfigError('Resource kinds %s cannot be exported to a portable project' % sorted(kinds - {'pa', 'i', 'zi', 'gmov'}))
    known = {n for _, n in pairs} | {n + 's' for k, n in pairs if k in ('i', 'gmov')} | {'main.HMI', 'Program.s'}
    extra = [n for n in files if n not in known]
    if extra:
        raise C.ConfigError('Files outside the project index cannot be exported to a portable project: %s' % ', '.join(extra[:5]))
    page_files = [n for k, n in pairs if k == 'pa']
    pages = [M.parse_page(files[n]) for n in page_files]
    used = set()

    def unique(raw, fallback):
        key, n = _slug(raw, fallback), 1
        base = key
        while key in used:
            n += 1
            key = '%s_%d' % (base, n)
        used.add(key)
        return key
    page_keys = [unique(p.name, f) for p, f in zip(pages, page_files)]
    used.clear()
    pic_files = [n for k, n in pairs if k == 'i']
    pic_keys = [unique('pic_' + n[:-2], n) for n in pic_files]
    used.clear()
    font_files = [n for k, n in pairs if k == 'zi']
    font_keys = [unique('font_' + n[:-3], n) for n in font_files]
    used.clear()
    anim_files = [n for k, n in pairs if k == 'gmov']
    anim_keys = [unique('anim_' + n[:-5], n) for n in anim_files]
    obj_keys = []
    for page in pages:
        used = set()
        keys = ['(page)']
        for i, o in enumerate(page.objects[1:], 1):
            name = o.get('objname').value.decode('utf8', 'replace') if o.get('objname') else 'obj%d' % i
            key, n = _slug(name, 'obj%d' % i), 1
            base = key
            while key in used or key == '(page)':
                n += 1
                key = '%s_%d' % (base, n)
            used.add(key)
            keys.append(key)
        obj_keys.append(keys)
    symbols = _Symbols(page_keys, pic_keys, font_keys, obj_keys, anim_keys)
    maps = _identity_maps(len(pages), len(pic_files), len(font_files), [len(p.objects) for p in pages], [p.name for p in pages])

    def code_line(raw, page_index):
        rw = R.Rewriter(maps, page_index, symbolize=symbols.placeholder)
        text = raw.decode('utf8', 'surrogateescape')
        return rw.run(text)

    def line_json(raw, page_index):
        try:
            raw.decode('utf8')
        except UnicodeDecodeError:
            return {'hex': raw.hex()}
        return code_line(raw, page_index)

    def attr_json(obj, code):
        out = {}
        for a in obj.attrs:
            if a.name in ('type', 'id'):
                continue
            value = M.decode_value(a.name, a.value)
            dom = R.attr_domain(code, a.name)
            if dom and isinstance(value, int):
                ref = symbols.ref(dom[0], value)
                if ref and value != dom[1]:
                    value = {'$ref': ref}
            out[a.name] = value
        # endx/endy are derived when they follow x/y/w/h
        for end, a_, b_ in (('endx', 'x', 'w'), ('endy', 'y', 'h')):
            if all(k in out for k in (end, a_, b_)) and all(isinstance(out[k], int) for k in (end, a_, b_)) \
                    and out[end] == out[a_] + out[b_] - 1:
                del out[end]
        return out

    # layouts: the most common layout per type; deviating objects carry their own
    layouts, counts = {}, {}
    for page in pages:
        for o in page.objects:
            counts.setdefault(o.get('type').value[0], {}).setdefault(json.dumps(_layout_of(o)), 0)
            counts[o.get('type').value[0]][json.dumps(_layout_of(o))] += 1
    for code, c in counts.items():
        layouts[str(code)] = json.loads(max(c, key=c.get))
    page_docs = []
    for pi, (page, key) in enumerate(zip(pages, page_keys)):
        for o in page.objects:
            seen = [a.name for a in o.attrs]
            if len(seen) != len(set(seen)):
                raise C.ConfigError('Page %s has a component with a repeated attribute; it cannot be exported' % page.name)

        def obj_json(o, root=False):
            code = o.get('type').value[0]
            d = {} if root else {'key': obj_keys[pi][page.objects.index(o)], 'type': H.TYPES.get(code, code)}
            skip = ('objname',) if root and o.get('objname') and o.get('objname').value.decode('utf8', 'replace') == page.name else ()
            attrs = attr_json(o, code)
            for k in skip:
                attrs.pop(k, None)
            d['attributes'] = attrs
            d['events'] = {e.label: [line_json(x, pi) for x in e.lines] for e in o.events}
            lay = _layout_of(o)
            if lay != layouts[str(code)]:
                d['layout'] = lay
            if o.extra:
                d['extra'] = o.extra
            if o.tail != b'\0\0\0\0':
                d['tail'] = o.tail.hex()
            return d
        hdr = bytes(page.header)
        doc = {'name': page.name, 'header': {'lock': hdr[16:24].hex(), 'writer': hdr[40:56].hex()},
               'root': obj_json(page.objects[0], True), 'objects': [obj_json(o) for o in page.objects[1:]]}
        page_docs.append((key, doc))
    program = files.get('Program.s')
    program_text = None
    if program is not None:
        text = program.decode('utf8', 'surrogateescape')
        out = []
        for line in text.splitlines(True):
            body = line.rstrip('\r\n')
            out.append(code_line(body.encode('utf8', 'surrogateescape'), None) + line[len(body):])
        program_text = ''.join(out).encode('utf8', 'surrogateescape')
    pngs = []
    for f, key in zip(pic_files, pic_keys):
        png = C._source_png(files.get(f + 's'))
        if png is None:
            raise C.ConfigError('Picture %s has no PNG source (%ss) and cannot be exported' % (f, f))
        pngs.append((key, png))
    anims = []
    for f, key in zip(anim_files, anim_keys):
        try:
            src = ANIM.validate_source(files.get(f + 's', b''))
            gm = ANIM._parse(files[f], 'gmov')
            ms = [fr['duration_ms'] for fr in gm['frames']]
            if len(ms) != len(src['pngs']) or ms != [fr['duration_ms'] for fr in src['frames']]:
                raise ValueError('source and compiled frames differ')
            entry = {'fps': gm['fps'], 'frames': [{'png': 'animations/%s/%03d.png' % (key, i), 'ms': m}
                                                  for i, m in enumerate(ms)]}
            if gm['opaque']:
                entry['opaque'] = True
            anims.append((key, entry, src['pngs']))
        except ValueError:
            entry = {'gmov': 'animations/%s.gmov' % key}
            if f + 's' in files:
                entry['gmovs'] = 'animations/%s.gmovs' % key
            anims.append((key, entry, None))
    order = []
    for k, _ in pairs:
        if k not in order:
            order.append(k)
    config = {'format': C.FORMAT, 'portable': True,
              'project': {'header': bytes(index.header).hex(), 'index_order': order},
              'layouts': layouts,
              'pages': [{'key': k, 'content': {'mode': 'json', 'path': 'pages/%s.json' % k}} for k in page_keys],
              'pictures': [{'key': k, 'source': {'png': 'pictures/%s.png' % k}} for k in pic_keys],
              'fonts': [{'key': k, 'source': {'zi': 'fonts/%s.zi' % k}} for k in font_keys],
              'animations': [dict(key=k, **entry) for k, entry, _ in anims]}
    if program_text is not None:
        config['program'] = 'Program.s'
    destination.mkdir(parents=True)
    try:
        for sub in ('pages', 'pictures', 'fonts', 'animations'):
            (destination / sub).mkdir(parents=True)
        for key, doc in page_docs:
            (destination / 'pages' / (key + '.json')).write_bytes(P.json_bytes(doc))
        for key, png in pngs:
            (destination / 'pictures' / (key + '.png')).write_bytes(png)
        for f, key in zip(font_files, font_keys):
            (destination / 'fonts' / (key + '.zi')).write_bytes(files[f])
        for f, (key, entry, frames) in zip(anim_files, anims):
            if frames is not None:
                (destination / 'animations' / key).mkdir()
                for fr, png in zip(entry['frames'], frames):
                    (destination / fr['png']).write_bytes(png)
            else:
                (destination / entry['gmov']).write_bytes(files[f])
                if 'gmovs' in entry:
                    (destination / entry['gmovs']).write_bytes(files[f + 's'])
        if program_text is not None:
            (destination / 'Program.s').write_bytes(program_text)
        (destination / 'project.json').write_bytes(P.json_bytes(config))
    except BaseException:
        shutil.rmtree(destination, ignore_errors=True)
        raise
    return {'directory': str(destination), 'pages': len(pages), 'pictures': len(pic_files), 'fonts': len(font_files),
            'animations': len(anim_files)}


