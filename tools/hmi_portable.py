#!/usr/bin/env python3
"""Portable (source-only) projects: everything needed to rebuild a display project lives in editable assets.

python3 hmi_project.py unpack --portable project.HMI dir      # PNG pictures, JSON pages, text script, binary fonts/animations
python3 hmi_project.py pack dir result.HMI --config project.json

A portable directory needs no original `.HMI`, no `files/` and no manifest, so it can be committed to Git as is:

  project.json              ordered pages / pictures / fonts / animations, per-type attribute layouts, project header
  pages/<key>.json          one lossless, human-editable file per page
  pictures/<key>.png        pictures as PNG (compiled `.i` + `.is` are generated)
  fonts/<key>.zi            compiled fonts (there is no TTF source for them; or use a `ttf` source)
  animations/<key>/NNN.png  animation frames (compiled `.gmov` + `.gmovs` are generated by hmi_anim.py)
  Program.s                 startup script

Ids are never written as numbers: attributes use {"$ref": "picture:KEY"} and code uses ${page:KEY}, ${picture:KEY},
${font:KEY}, ${obj:PAGE/OBJECT}; the position in each list is the id. Inserting, deleting and reordering therefore needs
no renumbering. A page file keeps what the format stores (attribute order and widths via `layouts`, header bytes, table
words, trailers), so rebuilding an unedited project gives byte-identical pages, `Program.s`, fonts and animations.
Pictures are re-encoded from their PNG (Pillow), which is not byte-identical to the editor's compressor; file names and
the order of files inside the container are chosen by this tool.
"""
